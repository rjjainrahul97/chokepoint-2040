// Dev-only: regenerates src/map-data.js. The live site never loads these libraries.
// Usage: npm i d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2 in any folder, then
//        node tools/make-map.mjs <that-folder>/node_modules
import {createRequire} from 'node:module';
import {writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
const dir=process.argv[2]&&resolve(process.argv[2]);if(!dir)throw Error('Pass the node_modules folder that holds d3-geo, topojson-client and world-atlas');
const req=createRequire(join(dir,'x.js'));
const {geoNaturalEarth1,geoPath,geoArea}=await import(new URL('file:///'+req.resolve('d3-geo').replace(/\\/g,'/')).href);
const topo=req('topojson-client'),world=req('world-atlas/countries-110m.json');
const IDS={india:'356',usa:'840',china:'156',germany:'276',france:'250',saudi:'682',uae:'784',japan:'392',korea:'410',australia:'036',indonesia:'360',brazil:'076'};
const all=topo.feature(world,world.objects.countries).features.filter(f=>f.id!=='010'); // drop Antarctica
const W=1000,H=470,projection=geoNaturalEarth1().fitExtent([[4,4],[W-4,H-4]],{type:'FeatureCollection',features:all});
const path=geoPath(projection).digits(0);
const land=path(topo.merge(world,world.objects.countries.geometries.filter(g=>g.id!=='010')));
const countries={},centres={};
for(const [key,id] of Object.entries(IDS)){const f=all.find(x=>x.id===id);countries[key]=path(f);
 // Label at the largest polygon so France sits in Europe, not French Guiana.
 const parts=f.geometry.type==='MultiPolygon'?f.geometry.coordinates.map(c=>({type:'Polygon',coordinates:c})):[f.geometry];
 const main=parts.sort((a,b)=>geoArea(b)-geoArea(a))[0];centres[key]=path.centroid(main).map(Math.round);}
writeFileSync(new URL('../src/map-data.js',import.meta.url),`/* Generated by tools/make-map.mjs from world-atlas 110m (Natural Earth, public domain). Do not edit. */\nexport const MAP={width:${W},height:${H},land:${JSON.stringify(land)},countries:${JSON.stringify(countries)},centres:${JSON.stringify(centres)}};\n`);
console.log('map-data.js written');
